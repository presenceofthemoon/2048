"""Модуль для работы с плитками игры 2048."""


class Tile:
    """
    Представляет одну плитку на игровом поле.
    
    Каждая плитка имеет значение (2, 4, 8, 16...) и позицию на сетке.
    Флаг merged используется для предотвращения множественного слияния за один ход.
    """
    
    def __init__(self, value: int = 2, x: int = 0, y: int = 0):
        """
        Создает новую плитку.
        
        Args:
            value: Числовое значение плитки (по умолчанию 2)
            x: Координата X на сетке (столбец)
            y: Координата Y на сетке (строка)
        """
        self.value = value
        self.x = x
        self.y = y
        self.merged = False
    
    def double(self):
        """Удваивает значение плитки и помечает как объединенную."""
        self.value *= 2
        self.merged = True
    
    def reset_merged(self):
        """Сбрасывает флаг объединения для следующего хода."""
        self.merged = False
    
    def __repr__(self):
        return f"Tile({self.value})"